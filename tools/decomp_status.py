#!/usr/bin/env python3
"""Compile-readiness report for one decomp module (CMake target `main_rel_status`).

Compiles every code TU of external/fzero-gx-decomp/src/rel/<module>/ with the port's decomp
environment (mwcc_shim.h, header overrides, 64-bit hazard errors) in syntax-only mode and writes
a Markdown burn-down: per-TU error counts and first error, error classes, clean TUs.
"""

from __future__ import annotations

import argparse
import collections
import concurrent.futures
import os
import re
import subprocess
import sys
from pathlib import Path

QUOTED = re.compile(r"‘[^’]*’|'[^']*'")


def compile_tu(cc: str, base_args: list[str], tu: Path, cwd: Path) -> list[str]:
    result = subprocess.run([cc, *base_args, str(tu)], capture_output=True, text=True, cwd=cwd)
    return [line for line in result.stderr.splitlines() if " error: " in line or line.startswith("error:")]


def error_class(line: str) -> str:
    message = line.split("error: ", 1)[1] if "error: " in line else line
    return QUOTED.sub("X", message).strip()


def relative(line: str, roots: list[Path]) -> str:
    for root in roots:
        line = line.replace(str(root) + os.sep, "")
    return line


def md_cell(text: str) -> str:
    return text.replace("|", "\\|")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cc", required=True)
    parser.add_argument("--decomp", required=True, type=Path)
    parser.add_argument("--module", required=True)
    parser.add_argument("--shim", required=True)
    parser.add_argument("--include-dirs", nargs="+", default=[])
    parser.add_argument("--flag", action="append", default=[], help="extra compiler flag (repeatable)")
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()

    module_dir = args.decomp / "src" / "rel" / args.module
    tus = sorted(module_dir.glob("*.c"))
    if not tus:
        print(f"no TUs in {module_dir}", file=sys.stderr)
        return 1

    # No -w: it would also silence the -Werror=... hazards. Only error lines are counted.
    base_args = ["-std=gnu11", "-fsyntax-only", "-fmax-errors=0", "-include", args.shim, *args.flag]
    base_args += [f"-I{d}" for d in args.include_dirs]

    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        futures = {tu: pool.submit(compile_tu, args.cc, base_args, tu, args.decomp) for tu in tus}
        errors = {tu.name: futures[tu].result() for tu in tus}

    repo_root = args.out.resolve().parent.parent
    roots = [args.decomp.resolve(), repo_root]
    decomp_rev = subprocess.run(["git", "-C", str(args.decomp), "rev-parse", "--short=9", "HEAD"],
                                capture_output=True, text=True).stdout.strip() or "unknown"
    cc_version = subprocess.run([args.cc, "--version"], capture_output=True, text=True).stdout.splitlines()
    cc_version_line = cc_version[0] if cc_version else args.cc

    total = sum(len(v) for v in errors.values())
    clean = [name for name, v in errors.items() if not v]
    classes = collections.Counter()
    class_tus = collections.defaultdict(set)
    first_classes = collections.Counter()
    for name, lines in errors.items():
        for line in lines:
            cls = error_class(line)
            classes[cls] += 1
            class_tus[cls].add(name)
        if lines:
            first_classes[error_class(lines[0])] += 1

    out = []
    out.append(f"# `{args.module}` native compile status\n")
    out.append("Generated by `cmake --build --preset linux-debug --target main_rel_status` "
               "(tools/decomp_status.py). Do not edit by hand.\n")
    out.append(f"- Decomp revision: `{decomp_rev}`; compiler: `{cc_version_line}`")
    out.append("- Environment: `mwcc_shim.h` force-included, `include/fzgx_port/decomp_overrides/` before "
               "the decomp headers, errors: " + ", ".join(f"`{f}`" for f in args.flag))
    out.append(f"- **TUs compiling: {len(clean)} / {len(tus)}**; errors: {total}\n")

    out.append("## First error per failing TU, by class\n")
    out.append("The first error is the one to fix: later ones are often its consequences.\n")
    out.append("| TUs | First error class |")
    out.append("|---:|---|")
    for cls, count in first_classes.most_common():
        out.append(f"| {count} | {md_cell(cls)} |")

    out.append("\n## All errors by class (top 25)\n")
    out.append("| Errors | TUs | Class |")
    out.append("|---:|---:|---|")
    for cls, count in classes.most_common(25):
        out.append(f"| {count} | {len(class_tus[cls])} | {md_cell(cls)} |")

    out.append("\n## Per TU\n")
    out.append("| TU | Errors | First error |")
    out.append("|---|---:|---|")
    for name, lines in sorted(errors.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        first = md_cell(relative(lines[0], roots)) if lines else ""
        out.append(f"| `{name}` | {len(lines)} | {first} |")

    out.append("\n## Clean TUs\n")
    out.append(", ".join(f"`{name}`" for name in clean) if clean else "None.")
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{args.module}: {len(clean)}/{len(tus)} TUs compile, {total} errors -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
